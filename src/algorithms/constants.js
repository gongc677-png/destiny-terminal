export function getShiShen(dayStem, otherStem) {
  const dayElem = STEM_ELEMENT[dayStem];
  const otherElem = STEM_ELEMENT[otherStem];
  const sameYinYang = YIN_YANG[dayStem] === YIN_YANG[otherStem];
  const pair = SHISHEN_MAP[dayElem][otherElem];
  return sameYinYang ? pair[0] : pair[1];
}

